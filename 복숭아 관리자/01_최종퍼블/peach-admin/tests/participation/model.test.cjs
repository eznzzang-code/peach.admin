const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const context={window:{}};vm.createContext(context);
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname,'../../js/participation/model.js'),'utf8'),context);
const M=context.window.PeachSurveyModel;
const f=M.seed();
assert.equal(M.validate(f).length,0,'seed passes validation');
assert.equal(M.next(f,f.questions[1],'yes'),'q2a');
assert.equal(M.next(f,f.questions[1],'no'),'q3');
assert.equal(M.next(f,f.questions[2],'field training'),'q3');
assert.equal(M.next(f,f.questions[3],['a']),null);
assert.equal(JSON.stringify(M.trace(f,{q1:'백도',q2:'no',q3:['a']})),JSON.stringify(['q1','q2','q3']));
assert.equal(JSON.stringify(M.trace(f,{q1:'백도',q2:'yes',q2a:'교육',q3:['b']})),JSON.stringify(['q1','q2','q2a','q3']));
const broken=M.clone(f);broken.questions.splice(2,1);
assert(M.validate(broken).some(e=>e.includes('목적지')),'deleted branch destination rejected');
const cyclic=M.clone(f);cyclic.questions[1].options[0].to='q1';
assert(M.validate(cyclic).some(e=>e.includes('목적지')),'backward destination rejected');
assert.throws(()=>M.trace(cyclic,{q1:'x',q2:'yes'}),/순환/);
const unreachable=M.clone(f);unreachable.questions[1].options.forEach(o=>o.to='q3');
assert(M.validate(unreachable).some(e=>e.includes('도달')),'unreachable question rejected');
const event=M.seed('event');event.questions=[M.attendanceQuestion()];
assert.equal(M.validate(event).length,0,'event allows no additional questions');
const emptySurvey=M.seed();emptySurvey.questions=[];
assert(M.validate(emptySurvey).length>0,'survey requires questions');
const end=M.clone(f);end.questions[0].next='submit';
assert.equal(M.next(end,end.questions[0],'x'),null);
assert.equal(f.consent.included,true,'privacy consent included by default');
assert.equal(M.consentAllowsSubmit(f,false),false,'included consent cannot be bypassed');
assert.equal(M.consentAllowsSubmit(f,true),true);
const noConsent=M.clone(f);noConsent.consent.included=false;
assert.equal(M.consentAllowsSubmit(noConsent,false),true,'excluded consent does not block submission');
const missingConsent=M.clone(f);missingConsent.consent.purpose='';assert(M.validate(missingConsent,{publish:true}).some(e=>e.includes('개인정보')),'publication requires consent notice content');
const completeConsent=M.clone(f);Object.assign(completeConsent.consent,{purpose:'테스트 목적',items:'테스트 항목',retention:'테스트 기간'});
assert.equal(M.validate(completeConsent,{publish:true}).length,0);
const migrated=M.clone(f);delete migrated.consent;M.prepare(migrated);
assert.equal(migrated.consent.included,true,'old forms receive default consent without deleting data');
assert.equal(migrated.questions.length,4);
console.log('PASS: default consent, include/exclude toggle, consent submission gate, publication notice validation, backward-compatible migration.');
console.log('PASS: Y/N branching, path traversal, final submission, deleted targets, backward/cyclic routes, unreachable questions, and events with only fixed attendance.');

assert.equal(M.autoEnd('2026-10-27T09:00'),'2027-10-27T09:00');
assert.equal(M.autoEnd('2024-02-29T12:30'),'2025-02-28T12:30','leap date clamps to final February day');
const annual=M.seed();annual.settings.start='2026-10-27T09:00';annual.settings.endMode='auto';annual.publishedAt='2026-10-27T09:00';annual.isPublic=true;
assert.equal(M.status(annual,new Date('2027-10-27T08:59')),'live');
assert.equal(M.status(annual,new Date('2027-10-27T09:00')),'closed','automatic closing at one-year boundary');
const overYear=M.seed();overYear.settings.endMode='manual';overYear.settings.end='2028-10-27T09:00';assert(M.validate(overYear).some(e=>e.includes('최대 1년')));
console.log('PASS: optional end date, annual automatic closing, leap-day boundary, maximum one-year manual period.');
